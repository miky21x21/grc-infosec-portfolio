# Uncommitted files are tolerated here (the local HTML tool lives untracked),
# but anything already staged would get swept into this commit.
if [ -n "$(git diff --cached --name-only)" ]; then
  echo "error: you have staged changes. Commit or unstage them first:" >&2
  git diff --cached --name-only >&2; exit 1
fi

if ! git config user.name >/dev/null || ! git config user.email >/dev/null; then
  echo "error: git identity not set." >&2; exit 1
fi

command -v base64 >/dev/null || { echo "error: base64 not found" >&2; exit 1; }

echo "repo: $(pwd)"
echo

write_file() {
  local path="$1"
  mkdir -p "$(dirname "$path")"
  base64 -d > "$path"
  echo "wrote  $path"
}

mkdir -p divine-healthcare/06_Decisions
echo "ready  divine-healthcare/06_Decisions"
echo

