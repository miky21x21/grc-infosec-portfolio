# ---------------------------------------------------------------------------
# setup-dh-dec-001.sh
#
# Adds divine-healthcare/06_Decisions/ and DH-DEC-001, and corrects the
# engagement README's artifact table to match DEC-001 (single combined
# standard, DH-STD-002 unallocated).
